def trim(rows):
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    # trim fully empty columns on the right (keep at least 1)
    while w > 1 and all(r[w - 1] == '.' for r in rows):
        w -= 1
    return [r[:w] for r in rows], w


# hand-made bold forms for glyphs that clog when smeared
BOLD_OVERRIDE = {
    'm': (2, ["#######.", "##.##.##", "##.##.##", "##.##.##", "##.##.##"]),
    'w': (2, ["##.##.##", "##.##.##", "##.##.##", "##.##.##", ".##..##."]),
    'M': (0, ["##...##", "###.###", "##.#.##", "##.#.##", "##...##", "##...##", "##...##"]),
    'W': (0, ["##...##", "##...##", "##...##", "##.#.##", "##.#.##", "###.###", "##...##"]),
    'N': (0, ["##..##", "###.##", "######", "##.###", "##..##", "##..##", "##..##"]),
}


def build(glyphs, name, face, cell_h, line_h, base, space_w, bold=False, top_pad=1):
    """Pack glyphs into an atlas and write BMFont text. base = ascent (px from line top to baseline)."""
    items = []
    for ch, (top, rows) in glyphs.items():
        rows, w = trim(rows)
        if bold and ch in BOLD_OVERRIDE:
            top, rows = BOLD_OVERRIDE[ch]
            rows, w = trim(rows)
        elif bold:
            rows = [''.join('#' if (r[i] == '#' if i < len(r) else False) or (i > 0 and i - 1 < len(r) and r[i - 1] == '#') else '.'
                            for i in range(len(r) + 1)) for r in rows]
            w += 1
        items.append((ch, top, rows, w))
    atlas_w = 256
    x = y = 1
    placements = []
    row_h = cell_h + 1
    for ch, top, rows, w in items:
        if x + w + 1 > atlas_w:
            x = 1
            y += row_h + 1
        placements.append((ch, x, y, top, rows, w))
        x += w + 2
    atlas_h = 1
    while atlas_h < y + row_h + 2:
        atlas_h *= 2
    img = Image.new('RGBA', (atlas_w, atlas_h), (0, 0, 0, 0))
    px = img.load()
    for ch, gx, gy, top, rows, w in placements:
        for ry, r in enumerate(rows):
            for rx, c in enumerate(r):
                if c == '#':
                    px[gx + rx, gy + top + ry] = (255, 255, 255, 255)
    img.save(os.path.join(OUT, name + '.png'))
    lines = [
        f'info face="{face}" size={line_h} bold={1 if bold else 0} italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0',
        f'common lineHeight={line_h} base={base} scaleW={atlas_w} scaleH={atlas_h} pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4',
        f'page id=0 file="{name}.png"',
        f'chars count={len(placements) + 1}',
        f'char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={space_w + (1 if bold else 0)} page=0 chnl=15',
    ]
    for ch, gx, gy, top, rows, w in placements:
        lines.append(f'char id={ord(ch)} x={gx} y={gy} width={w} height={cell_h} xoffset=0 yoffset={top_pad} xadvance={w + 1} page=0 chnl=15')
    with open(os.path.join(OUT, name + '.fnt'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(name, len(placements), 'glyphs', atlas_w, 'x', atlas_h)


